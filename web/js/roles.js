'use strict';

/**
 * Роли пользователя: один ответ на вопрос «это администратор?» и «куда ведёт
 * вход» — для всех страниц сразу.
 *
 * Почему отдельным модулем. До него проверка роли была переписана в трёх
 * местах (`login.js`, `account-shell.js`, `admin-shell.js`) плюс guard на
 * сервере. Пока копии совпадают, это просто повтор; стоит одной отстать — и
 * сервис начинает вести себя по-разному на разных страницах: раздел открыт, а
 * вход в него не ведёт. Поэтому правило здесь одно и ссылается на него всё,
 * что работает в браузере.
 *
 * Серверная проверка (web/server.js) намеренно остаётся своей: это CommonJS в
 * Node, и она не импортирует браузерный модуль. Разъехаться им не страшно —
 * решает всё равно сервер, а эта копия только выбирает, что показать.
 *
 * Роли приходят СПИСКОМ (`user.roles`, собирается API по таблице
 * `user_roles`), поэтому вопрос — «есть ли роль в списке», а не «равна ли
 * роль администратору»: у одного человека их может быть несколько, например
 * мастер, который заодно администрирует.
 */

/** Роли, которым открыт раздел администратора — те же, что у requireRole в API. */
export const ADMIN_ROLES = ['admin', 'owner'];

/** Личный кабинет клиента — куда ведёт вход всех остальных. */
export const CABINET_PAGE = 'account.html';

/** Первая страница раздела администратора. */
export const ADMIN_PAGE = '/admin/appointments';

/** Есть ли у пользователя роль администратора или владельца. */
export function isAdmin(user) {
  return !!user && Array.isArray(user.roles)
    && ADMIN_ROLES.some((role) => user.roles.includes(role));
}

/**
 * Куда ведёт сервис человека с такими ролями.
 *
 * @param {object|null} user профиль из `POST /auth/login` или `GET /auth/me`
 * @param {string} [fallback] куда вести всех, кроме администратора
 */
export function homePageFor(user, fallback = CABINET_PAGE) {
  return isAdmin(user) ? ADMIN_PAGE : fallback;
}
